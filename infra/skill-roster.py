#!/usr/bin/env python3
"""skill-roster.py — generate ~/.openclaw/.skill-roster.json.

The roster maps every `user-skills/<slug>/{SKILL.md, eval.yaml}` in the
repo to its sha256 content hash. It's the source-of-truth manifest used
by `skill-write-audit.sh` to detect bypass writes to
`~/.openclaw/workspace/skills/<slug>/<file>`.

Regenerated by:
  - `infra/deploy-vps.sh:sync_user_skills()` at the end of each deploy
  - `meta/skill-author/scripts/commit-and-deploy.ts` after each commit
  - `infra/skill-write-audit.sh` at daemon startup as a safety net

Roster format (v1):
{
  "version": 1,
  "generated_at": "2026-05-20T16:00:00Z",
  "skills": {
    "<slug>": {
      "SKILL.md": "<sha256-hex>",
      "eval.yaml": "<sha256-hex>"
    },
    ...
  }
}

The audit daemon reads this file, walks workspace/skills/<slug> for
every slug in the roster, and compares the on-disk hash to the
expected hash. Mismatch → revert from repo + send a Telegram warning.
"""

from __future__ import annotations
import hashlib
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


def main() -> int:
    repo = Path(os.environ.get("REPO") or str(Path.home() / "personal-assistant"))
    out = Path(os.environ.get("ROSTER_FILE") or str(Path.home() / ".openclaw" / ".skill-roster.json"))

    user_skills_dir = repo / "user-skills"
    if not user_skills_dir.is_dir():
        # Repo doesn't have user-skills/ yet — write an empty roster so
        # the daemon doesn't get confused by a missing file.
        skills: dict[str, dict[str, str]] = {}
    else:
        skills = {}
        for slug_dir in sorted(user_skills_dir.iterdir()):
            if not slug_dir.is_dir():
                continue
            slug = slug_dir.name
            # Skip the README.md and .gitkeep at the user-skills/ root —
            # they're not slug dirs.
            entry: dict[str, str] = {}
            for fname in ("SKILL.md", "eval.yaml"):
                p = slug_dir / fname
                if not p.is_file():
                    continue
                entry[fname] = hashlib.sha256(p.read_bytes()).hexdigest()
            if entry:
                skills[slug] = entry

    roster = {
        "version": 1,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "skills": skills,
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(roster, indent=2) + "\n")
    print(f"roster: {len(skills)} skill(s) → {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
